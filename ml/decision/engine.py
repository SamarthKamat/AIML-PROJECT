"""Business Decision Engine - converts a supplier risk prediction into a traceable recommendation.

Workflow (every step is computed, nothing is generated by an LLM):
  1  identify supplier                      8  inventory coverage of reached materials
  2  establish prediction timestamp t        9  alternative suppliers (same / substitute material)
  3  point-in-time features (records < t)   10  operational consequence: cascade simulation of a
  4  raw disruption probability (XGBoost)       qualifying disruption (no intervention)
  5  calibrated probability (Platt/iso)     11  recovery optimisation (MILP) if action >= High
  6  risk category = cost-minimising action 12  recommended action + allocation + cost
  7  material criticality                   13  decision record with assumptions & versions
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from functools import lru_cache

import joblib
import numpy as np
import pandas as pd

from ml.common.config import EXPERIMENTS, MODELS, SYN
from ml.data_engineering.features_supplier import FEATURES, build_snapshot_features, load_tables
from ml.decision.exposure import ExposureModel
from ml.decision.policy import ACTIONS, break_even_probabilities, choose_action
from ml.optimisation.recovery import build_candidates, load_assumptions, material_penalty, optimise_recovery
from ml.simulation.cascade import CascadeSimulator, Disruption, load_network

MODEL_VERSION = "exp1_xgboost.joblib"


@lru_cache(maxsize=1)
def _tables():
    return load_tables()


@lru_cache(maxsize=1)
def _bundle():
    return joblib.load(MODELS / MODEL_VERSION)


@lru_cache(maxsize=1)
def _exposure():
    extra = None
    p = EXPERIMENTS / "exp2a_link_prediction" / "candidate_links.csv"
    if p.exists():
        sup = pd.read_csv(SYN / "suppliers.csv").set_index("supplier_id")
        tier = sup.tier.to_dict()
        tier["C001"] = 0
        cand = pd.read_csv(p).sort_values("rank").head(500)
        rows = []
        for a, b in zip(cand.node_a, cand.node_b):
            s, buyer = (a, b) if tier[a] > tier[b] else (b, a)
            rows.append(dict(supplier_id=s, buyer_id=buyer, material_id=sup.loc[s, "primary_material_id"],
                             dependency_pct=0.5, visibility="predicted"))
        extra = pd.DataFrame(rows)
    return ExposureModel(graph="observed"), ExposureModel(graph="observed", extra_edges=extra)


@lru_cache(maxsize=4)
def _sim(start):
    net = load_network(start=start)
    return net, CascadeSimulator(net, horizon=90)


def predict_risk(snapshot: pd.Timestamp, supplier_ids=None) -> pd.DataFrame:
    f = build_snapshot_features(_tables(), [snapshot])
    if supplier_ids is not None:
        f = f[f.supplier_id.isin(supplier_ids)]
    b = _bundle()
    p_raw = b["model"].predict_proba(f[b["features"]])[:, 1]
    f = f.assign(p_raw=p_raw, p_cal=b["calibrator"].predict(p_raw))
    return f


def _shap_row(features_row: pd.DataFrame, top=6):
    import shap
    expl = shap.TreeExplainer(_bundle()["model"])
    sv = expl.shap_values(features_row[FEATURES])[0]
    order = np.argsort(-np.abs(sv))[:top]
    return [dict(feature=FEATURES[i], value=None if pd.isna(features_row[FEATURES[i]].iloc[0]) else float(features_row[FEATURES[i]].iloc[0]),
                 shap_log_odds=round(float(sv[i]), 4)) for i in order]


def evaluate(supplier_id: str, timestamp: str = "2025-12-01", use_predicted_links: bool = True,
             simulate: bool = True) -> dict:
    A = load_assumptions()
    ts = pd.Timestamp(timestamp).normalize().replace(day=1)
    sup = _tables()["suppliers"].set_index("supplier_id")
    if supplier_id not in sup.index:
        raise KeyError(f"unknown supplier {supplier_id}")
    f = predict_risk(ts, [supplier_id])
    row = f.iloc[0]
    em_obs, em_pred = _exposure()
    em = em_pred if use_predicted_links else em_obs
    exp = em.exposure(supplier_id)
    act = choose_action(float(row.p_cal), exp["exposure_inr"])
    mats = pd.read_csv(SYN / "materials.csv").set_index("material_id")
    material_exposure = [dict(material_id=m, material_name=mats.loc[m, "material_name"], criticality=mats.loc[m, "criticality"], **d)
                         for m, d in sorted(exp["materials"].items(), key=lambda kv: -kv[1]["expected_loss_inr"])]
    out = dict(
        supplier_id=supplier_id, supplier_name=sup.loc[supplier_id, "supplier_name"], tier=int(sup.loc[supplier_id, "tier"]),
        prediction_timestamp=ts.isoformat(), information_cutoff="records with reported/delivery date < prediction timestamp",
        model_version=MODEL_VERSION, calibration_method=_bundle()["calibration_method"],
        disruption_probability=round(float(row.p_raw), 4), calibrated_probability=round(float(row.p_cal), 4),
        risk_category=act["risk_category"], recommended_action=act["action"],
        action_description=ACTIONS[act["action"]]["description"], expected_cost_by_action_inr=act["expected_cost_by_action_inr"],
        break_even_probabilities=break_even_probabilities(exp["exposure_inr"]),
        network_exposure_inr=exp["exposure_inr"], exposure_graph="observed + predicted candidate links" if use_predicted_links else "observed",
        material_exposure=material_exposure, top_feature_contributions=_shap_row(f.iloc[[0]]),
        data_label="SYNTHETIC demonstration data; INR values are simulated, not company losses",
    )
    if simulate:
        out.update(_consequences(supplier_id, ts, act["action"], material_exposure, A))
    out["decision_rationale"] = _rationale(out)
    out["assumptions_ref"] = "experiments/scenario_assumptions.json"
    out["decided_at"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    return out


def _consequences(supplier_id, ts, action, material_exposure, A):
    start = max(pd.Timestamp("2024-02-05"), min(ts, pd.Timestamp("2025-09-29"))).strftime("%Y-%m-%d")
    net, sim = _sim(start)
    dur = 30
    o = sim.run([Disruption([supplier_id], 1.0, 0, dur)])
    reached = [m["material_id"] for m in material_exposure]
    cover = {m: round(float(sim.I0[sim.mi[m]] / sim.R[sim.mi[m]]), 1) for m in reached if m in sim.mi and sim.R[sim.mi[m]] > 0}
    short_units = {sim.mlist[j]: round(float(o["mat_short"][:, j].sum()), 1) for j in range(len(sim.mlist)) if o["mat_short"][:, j].sum() > 0}
    cm = net.cm_unit.reindex(sim.plist).values
    res = dict(inventory_coverage_days=cover,
               consequence_simulation=dict(assumed_disruption="100% capacity loss for 30 days, no intervention",
                                           expected_material_shortage_units=short_units,
                                           unmet_demand_units=round(float(o["unmet"].sum()), 0),
                                           lost_contribution_margin_inr=round(float((o["unmet"].sum(0) * cm).sum()), 0),
                                           affected_suppliers=int((o["A"].min(0) < 0.99).sum()),
                                           min_service_level=round(float(o["fill"].min()), 4)))
    # alternatives & recovery plan
    risk = predict_risk(ts).set_index("supplier_id").p_cal
    subs = pd.read_csv(SYN / "material_substitutes.csv")
    t1_mats = [m for m in reached if m in sim.mi][:4]
    exclude = {supplier_id}
    cands = {m: build_candidates(net, m, exclude, risk, A, subs) for m in t1_mats}
    res["alternative_suppliers"] = [dict(material_id=m, supplier_id=c["supplier_id"], supplier_name=c["supplier_name"],
                                         supplies_material=c["supplies_material"], compatibility=c["compat"],
                                         spare_capacity_per_day=round(c["spare_daily"], 1), unit_price_inr=round(c["unit_price"], 2),
                                         lead_time_days=c["modes"]["standard"]["lead"], reliability=c["reliability"],
                                         calibrated_risk_p30=round(c["risk_p30"], 4), onboarding_required=c["onboarding"])
                                    for m, cs in cands.items() for c in sorted(cs, key=lambda c: c["risk_p30"])[:6]]
    if action in ("contingency_review", "escalate_recovery"):
        deficits = {m: float(o["mat_short"][:, sim.mi[m]].sum()) * 1.1 for m in t1_mats}
        deficits = {m: v for m, v in deficits.items() if v > 0}
        if not deficits:  # protect against the shortfall the buffer would only partly absorb
            deficits = {m: 0.3 * dur * float(sim.R[sim.mi[m]]) * float(e["reach"]) for m, e in
                        ((x["material_id"], x) for x in material_exposure) if m in t1_mats}
        orders, info = optimise_recovery(deficits, cands, dur + 15, material_penalty(net, A), A)
        res["recovery_plan"] = dict(solver=info, deficits_units={k: round(v, 1) for k, v in deficits.items()},
                                    allocation=[dict(supplier_id=x["supplier_id"], material_id=x["material_id"],
                                                     supplies_material=x.get("supplies_material", x["material_id"]),
                                                     qty=round(x["qty"], 1), mode=x["mode"], lead_days=x["lead_days"],
                                                     cost_inr=round(x["qty"] * x["unit_price"] * (1 + x["freight_rate"]) + x["fixed_cost"], 0))
                                                for x in orders],
                                    estimated_recovery_cost_inr=round(sum(x["qty"] * x["unit_price"] * (1 + x["freight_rate"]) + x["fixed_cost"]
                                                                          for x in orders), 0))
    else:
        res["recovery_plan"] = None
    return res


def _rationale(o):
    feats = ", ".join(f"{c['feature']} ({'+' if c['shap_log_odds'] > 0 else ''}{c['shap_log_odds']})" for c in o["top_feature_contributions"][:3])
    s = (f"Calibrated 30-day disruption probability {o['calibrated_probability']:.1%} (raw {o['disruption_probability']:.1%}). "
         f"Network exposure if disrupted: INR {o['network_exposure_inr']:,.0f} via {len(o['material_exposure'])} Tier-1 material(s). "
         f"Expected-cost minimisation selects '{o['recommended_action']}' ({o['risk_category']}). Main drivers: {feats}.")
    cs = o.get("consequence_simulation")
    if cs:
        s += f" A 30-day full outage would leave {cs['unmet_demand_units']:,.0f} units unmet (no intervention)."
    if o.get("recovery_plan"):
        s += f" Recovery MILP status {o['recovery_plan']['solver']['status']}, cost INR {o['recovery_plan']['estimated_recovery_cost_inr']:,.0f}."
    return s


if __name__ == "__main__":
    print(json.dumps(evaluate("S0122", "2025-12-01"), indent=2, default=str)[:4000])
